@pytest.mark.asyncio
async def test_agent_builds_bounded_plan_with_one_correction() -> None:
    async def handler(_: BaseModel) -> dict[str, Any]:
        return {}

    generator = _SequenceGenerator(
        (
            "invalid",
            '{"goal":"하드 보스 준비","steps":["캐릭터 조회","근거 비교"]}',
        )
    )
    service = NexonAgentService(generator, _registry(handler))

    result = await service.plan("보스 준비를 도와줘")

    assert result.plan.goal == "하드 보스 준비"
    assert result.plan.steps == ["캐릭터 조회", "근거 비교"]
    assert len(generator.calls) == 2


