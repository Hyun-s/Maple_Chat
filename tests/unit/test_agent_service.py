@pytest.mark.asyncio
async def test_agent_reconstructs_prior_steps_without_repeating_tool() -> None:
    executions = 0

    async def handler(_: BaseModel) -> dict[str, Any]:
        nonlocal executions
        executions += 1
        return {}

    generator = _SequenceGenerator(
        ('{"action":"finish","answer":"저장된 조회 결과로 완료했습니다."}',)
    )
    service = NexonAgentService(generator, _registry(handler), max_tool_calls=2)
    previous = AgentStep(1, "lookup", {"value": "x"}, {"official_value": 290})

    result = await service.run("질문", prior_steps=(previous,))

    assert executions == 0
    assert len(result.steps) == 1
    assert "official_value" in generator.calls[0][-1].content
