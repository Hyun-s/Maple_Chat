from __future__ import annotations

from collections.abc import Awaitable, Callable
from typing import Any

import pytest
from pydantic import BaseModel, ConfigDict, Field

from maple_chat.agent.service import AgentPlanningError, AgentStep, NexonAgentService
from maple_chat.agent.tools import ToolRegistry, ToolSpec
from maple_chat.llm.client import ChatMessage


class _Args(BaseModel):
    model_config = ConfigDict(extra="forbid")

    value: str = Field(min_length=1)


class _SequenceGenerator:
    def __init__(self, responses: tuple[str, ...]) -> None:
        self.responses = list(responses)
        self.calls: list[tuple[ChatMessage, ...]] = []

    async def generate(self, messages: tuple[ChatMessage, ...], *, max_tokens: int = 1024) -> str:
        self.calls.append(messages)
        return self.responses.pop(0)


def _registry(
    handler: Callable[[BaseModel], Awaitable[dict[str, Any]]],
    *,
    name: str = "lookup",
) -> ToolRegistry:
    return ToolRegistry(
        (
            ToolSpec(
                name=name,
                description="테스트 조회",
                input_model=_Args,
                handler=handler,
            ),
        )
    )


@pytest.mark.asyncio
async def test_agent_chooses_tool_evaluates_result_and_finishes() -> None:
    calls: list[str] = []

    async def handler(value: BaseModel) -> dict[str, Any]:
        args = _Args.model_validate(value)
        calls.append(args.value)
        return {"official_value": 290}

    generator = _SequenceGenerator(
        (
            '{"action":"tool","tool":"get_character_basic","arguments":{"value":"캐릭터"}}',
            '{"action":"finish","answer":"공식 조회 레벨은 290입니다."}',
        )
    )
    service = NexonAgentService(
        generator,
        _registry(handler, name="get_character_basic"),
        max_tool_calls=2,
    )

    result = await service.run("캐릭터 레벨을 알려줘")

    assert calls == ["캐릭터"]
    assert len(result.steps) == 1
    assert result.steps[0].result == {"official_value": 290}
    assert "공식 조회 레벨은 290" in result.text
    assert result.text.endswith("Data based on NEXON Open API")
    assert "official_value" in generator.calls[1][-1].content


