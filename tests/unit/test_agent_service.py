@pytest.mark.asyncio
async def test_agent_blocks_identical_tool_call_and_enforces_call_limit() -> None:
    executed = 0

    async def handler(value: BaseModel) -> dict[str, Any]:
        nonlocal executed
        executed += 1
        return {"value": _Args.model_validate(value).value}

    same = '{"action":"tool","tool":"lookup","arguments":{"value":"x"}}'
    generator = _SequenceGenerator(
        (same, same, '{"action":"finish","answer":"반복 호출을 중단했습니다."}')
    )
    service = NexonAgentService(generator, _registry(handler), max_tool_calls=2)

    result = await service.run("질문")

    assert executed == 1
    assert len(result.steps) == 2
    assert "반복할 수 없습니다" in str(result.steps[1].result)
    assert len(generator.calls) == 3


def test_agent_rejects_invalid_tool_call_limits() -> None:
    generator = _SequenceGenerator(())

    async def handler(_: BaseModel) -> dict[str, Any]:
        return {}

    registry = _registry(handler)
    with pytest.raises(ValueError, match="between one and eight"):
        NexonAgentService(generator, registry, max_tool_calls=0)
    with pytest.raises(ValueError, match="between one and eight"):
        NexonAgentService(generator, registry, max_tool_calls=9)


